/* ── Helper functions ── */
let _currentLang = 'en';

function setLang(lang) {
    if (TRANSLATIONS[lang]) _currentLang = lang;
}

function getLang() { return _currentLang; }

/** Get translation string */
function t(key) {
    return (TRANSLATIONS[_currentLang] || TRANSLATIONS.en)[key]
        || TRANSLATIONS.en[key]
        || key;
}

/** Get translation with variable substitution: tf('msgGotIt', { symptom: 'headache' }) */
function tf(key, vars = {}) {
    let str = t(key);
    for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return str;
}

/** Apply translations to all [data-i18n] elements in DOM */
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const attr = el.dataset.i18nAttr; // optional: 'placeholder', 'title', etc.
        const val  = t(key);
        if (attr) {
            el.setAttribute(attr, val);
        } else {
            el.textContent = val;
        }
    });
}
